CREATE OR REPLACE FUNCTION public.set_project_assignment_source(p_contractor integer, p_project integer, p_source text, p_owned boolean, p_assigned date DEFAULT CURRENT_DATE)
 RETURNS contractor_projects
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
 assignment public.contractor_projects;
 sources TEXT[];
BEGIN
 PERFORM pg_advisory_xact_lock(hashtext('contractor_project_ownership'));
 IF p_source IS NULL OR NOT EXISTS(SELECT 1 FROM relationship_sources WHERE source=p_source)
 OR p_owned IS NULL OR p_assigned IS NULL THEN
 RAISE EXCEPTION 'Invalid project ownership request';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM contractors WHERE id=p_contractor)
 OR NOT EXISTS(SELECT 1 FROM projects WHERE id=p_project) THEN
 RAISE EXCEPTION 'Contractor or project is unavailable';
 END IF;
 SELECT * INTO assignment FROM contractor_projects
 WHERE contractor_id=p_contractor AND project_id=p_project AND active FOR UPDATE;
 IF assignment.id IS NULL THEN
 IF NOT p_owned THEN RETURN NULL; END IF;
 INSERT INTO contractor_projects(contractor_id,project_id,assigned_date,active,ownership_sources)
 VALUES(p_contractor,p_project,p_assigned,true,ARRAY[p_source]) RETURNING * INTO assignment;
 ELSE
 sources := array_remove(assignment.ownership_sources,p_source);
 IF p_owned THEN sources := sources || ARRAY[p_source]; END IF;
 UPDATE contractor_projects SET
 ownership_sources=sources,
 active=cardinality(sources)>0,
 removed_date=CASE WHEN cardinality(sources)>0
 THEN NULL ELSE greatest(CURRENT_DATE,assigned_date) END
 WHERE id=assignment.id RETURNING * INTO assignment;
 END IF;
 RETURN assignment;
END;
$function$;

CREATE OR REPLACE FUNCTION public.import_project_without_classification(p_number text, p_name text, p_status text, p_existing integer DEFAULT NULL::integer)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE previous_context TEXT := current_setting('subtracker.project_import',true);
BEGIN
 IF NOT public.user_has_module_permission('imports','view')
 OR NOT public.user_has_module_permission('projects',CASE WHEN p_existing IS NULL THEN 'add' ELSE 'edit' END) THEN
 RAISE EXCEPTION 'Project import permission required' USING ERRCODE='42501';
 END IF;
 PERFORM set_config('subtracker.project_import','on',true);
 IF p_existing IS NULL THEN
 INSERT INTO public.projects(project_number,project_name,status) VALUES(p_number,p_name,p_status);
 ELSE
 UPDATE public.projects SET project_name=p_name,status=p_status WHERE id=p_existing;
 IF NOT FOUND THEN RAISE EXCEPTION 'Project not found' USING ERRCODE='P0002'; END IF;
 END IF;
 PERFORM set_config('subtracker.project_import',coalesce(previous_context,''),true);
END;
$function$
;
