 WHEN 'view' THEN permission.can_view
 WHEN 'add' THEN permission.can_add
 WHEN 'edit' THEN permission.can_edit
 WHEN 'delete' THEN permission.can_delete
 WHEN 'manage' THEN permission.can_manage
 ELSE FALSE
 END
 );
