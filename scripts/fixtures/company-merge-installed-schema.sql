CREATE OR REPLACE FUNCTION public.user_has_module_permission(p_module text, p_action text DEFAULT 'view'::text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
 SELECT EXISTS (
 SELECT 1
 FROM public.user_profiles AS profile
 JOIN public.role_permissions AS permission
 ON permission.role = profile.role
 WHERE profile.auth_user_id = auth.uid()
 AND profile.status = 'Active'
 AND permission.module = p_module
