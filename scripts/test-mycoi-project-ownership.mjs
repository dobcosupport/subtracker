const cache = new Map();
function load(name) {
  if (cache.has(name)) return cache.get(name);
  const loadedModule = { exports: {} };
  vm.runInNewContext(ts.transpileModule(read(name), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  }).outputText, { module: loadedModule, exports: loadedModule.exports, require: (id) => {
    if (id === "xlsx") return require("xlsx");
    if (id === "@/lib/mycoi-parser") return load("src/lib/mycoi-parser.ts");
    if (id === "@/lib/contractor-matching") return load("src/lib/contractor-matching.ts");
    if (id === "@/types/mycoi-import") return load("types/mycoi-import.ts");
    throw new Error(`Unexpected import ${id}`);
  } });
  cache.set(name, loadedModule.exports);
  return loadedModule.exports;
}
