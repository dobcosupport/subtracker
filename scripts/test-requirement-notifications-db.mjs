import assert from "node:assert/strict";

export async function testRequirementNotificationRules({ db, read, fails, actor, draftSQL, manualEmailDraft }) {
  const input = (value) => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
  await db.exec(`ALTER TABLE compliance_types ADD requires_expiration boolean NOT NULL DEFAULT true,ADD active boolean NOT NULL DEFAULT true;
    UPDATE compliance_types SET requires_expiration=false WHERE id IN(2,3);
    INSERT INTO compliance_types VALUES(4,'Retired fixture',true,false);
    UPDATE user_profiles SET system_administrator=true WHERE auth_user_id='${actor(1)}';
    GRANT SELECT ON compliance_types TO service_role;`);
  const legacy = (await db.query("SELECT * FROM notification_reminder_rules ORDER BY id")).rows;
  const channels = (await db.query("SELECT * FROM communication_channel_settings ORDER BY channel")).rows;
  const migration = read("20261208_requirement_notification_rules.sql");
  assert.doesNotMatch(migration, /cron\.schedule|pg_net|http_post|reserve_communication_email_send/i);
  await fails(migration.replace(/COMMIT;\s*$/, "SELECT 1/0; COMMIT;"), "22012");
  await db.exec("ROLLBACK");
  assert.equal((await db.query("SELECT to_regclass('requirement_notification_rules') x")).rows[0].x, null);
  await db.exec(migration);
  assert.deepEqual((await db.query("SELECT * FROM notification_reminder_rules ORDER BY id")).rows, legacy);
  assert.deepEqual((await db.query("SELECT * FROM communication_channel_settings ORDER BY channel")).rows, channels);
  const rules = (await db.query("SELECT * FROM requirement_notification_rules ORDER BY compliance_type_id NULLS LAST,insurance_item_key")).rows;
  assert.equal(rules.length, 7);
  assert.ok(rules.every(rule => !rule.automatic_enabled));
  assert.equal(rules.find(rule => rule.compliance_type_id === 2).schedule_type, "non_expiring");
  assert.deepEqual(rules.filter(rule => rule.insurance_item_key).map(rule => rule.insurance_item_key),
    ["certificate_of_insurance", "general_liability", "workers_compensation"]);
  const rule = rules.find(row => row.compliance_type_id === 1);
  const nonExpiring = rules.find(row => row.compliance_type_id === 2);
  const retired = rules.find(row => row.compliance_type_id === 4);
  const retiredInsurance = rules.find(row => row.insurance_item_key === "certificate_of_insurance");
  const template = actor(980);
  const approve = (n, revision) => `SELECT approve_communication_template_automation('${actor(n)}','${template}',${revision})`;
  const base = { compliance_type_id: 1, insurance_item_key: null, automatic_enabled: false, schedule_type: "expiration",
    sender_contact_id: null, internal_contact_id: null, revision: 1, intervals: [] };
  const save = (n, id, fields) => `SELECT save_requirement_notification_rule('${actor(n)}',${id ? `'${id}'` : "NULL"},${input(fields)})`;
  const enabled = { ...base, automatic_enabled: true, intervals: [{ days_before_expiration: 47, enabled: true, template_id: template }] };
  await db.exec("SET ROLE service_role");
  await fails(`INSERT INTO communication_template_automation_approvals VALUES('${template}',3,'${actor(1)}',now())`, "42501");
  await fails(approve(7, 3), "42501", "Settings manager is not necessarily an administrator");
  await fails(approve(2, 3), "42501");
  await fails(approve(1, 2), "PT409");
  await fails(save(1, rule.id, enabled), "22023");
  await fails(save(2, rule.id, base), "42501");
  await fails(save(1, nonExpiring.id, { ...enabled, compliance_type_id: 2, schedule_type: "non_expiring" }), "22023");
  await fails(save(1, nonExpiring.id, { ...base, compliance_type_id: 2, schedule_type: "expiration" }), "22023");
  await fails(save(1, retired.id, { ...enabled, compliance_type_id: 4 }), "22023");
  await fails(save(1, retiredInsurance.id, { ...enabled, compliance_type_id: null, insurance_item_key: "certificate_of_insurance" }), "22023");
  await fails(save(1, rule.id, { ...base, automatic_enabled: true }), "22023");
  await fails(save(1, rule.id, { ...base, intervals: [{ days_before_expiration: 30, enabled: true, template_id: null }] }), "22023");
  await db.exec(approve(1, 3));
  await db.exec("RESET ROLE");
  await db.exec(`UPDATE user_profiles SET role='Administrator' WHERE auth_user_id='${actor(7)}';
    INSERT INTO compliance_types VALUES(5,'Later requirement',true,true)`);
  await db.exec("SET ROLE service_role");
  await db.exec(approve(7, 3));
  const laterRule = (await db.query(save(1, null, { ...base, compliance_type_id: 5, revision: 0 }))).rows[0];
  assert.ok(laterRule.save_requirement_notification_rule, "Later authoritative types can be configured without another seed list");
  const approval = (await db.query(`SELECT * FROM communication_template_automation_approvals WHERE template_id='${template}'`)).rows[0];
  assert.equal(approval.template_revision, 3); assert.equal(approval.approved_by, actor(1)); assert.ok(approval.approved_at);
  await db.exec(save(1, rule.id, enabled));
  const stored = (await db.query(`SELECT * FROM requirement_notification_rules WHERE id='${rule.id}'`)).rows[0];
  assert.equal(stored.automatic_enabled, true); assert.equal(stored.revision, 2);
  assert.equal((await db.query(`SELECT configuration_ready FROM requirement_notification_readiness WHERE id='${rule.id}'`)).rows[0].configuration_ready, true);
  await fails(save(1, rule.id, enabled), "PT409");
  await db.exec("RESET ROLE");
  await db.exec(`UPDATE communication_templates SET revision=4,body='Changed after approval' WHERE id='${template}'`);
  assert.equal((await db.query(`SELECT count(*)::int n FROM communication_template_automation_approvals a
    JOIN communication_templates t ON t.id=a.template_id AND t.revision=a.template_revision
    WHERE t.id='${template}' AND t.is_active`)).rows[0].n, 0, "Old approvals never apply to a new revision");
  await db.exec("SET ROLE service_role");
  assert.equal((await db.query(`SELECT configuration_ready FROM requirement_notification_readiness WHERE id='${rule.id}'`)).rows[0].configuration_ready, false);
  await fails(save(1, rule.id, { ...enabled, revision: 2 }), "22023");
  await db.exec(approve(1, 4));
  assert.equal((await db.query(`SELECT configuration_ready FROM requirement_notification_readiness WHERE id='${rule.id}'`)).rows[0].configuration_ready, true);
  await db.exec("RESET ROLE");
  await db.exec(`UPDATE communication_templates SET is_active=false WHERE id='${template}'`);
  assert.equal((await db.query(`SELECT configuration_ready FROM requirement_notification_readiness WHERE id='${rule.id}'`)).rows[0].configuration_ready, false);
  await db.exec(`UPDATE communication_templates SET is_active=true,channel='sms',subject=NULL WHERE id='${template}'`);
  assert.equal((await db.query(`SELECT configuration_ready FROM requirement_notification_readiness WHERE id='${rule.id}'`)).rows[0].configuration_ready, false);
  await db.exec(`UPDATE communication_templates SET channel='email',subject='Original template subject' WHERE id='${template}'`);
  await db.exec("SET ROLE service_role");
  await db.exec(save(1, rule.id, { ...enabled, revision: 2 }));
  await db.exec(save(1, rule.id, { ...base, revision: 3, schedule_type: "non_expiring" }));
  assert.equal((await db.query(`SELECT count(*)::int n FROM requirement_notification_intervals WHERE rule_id='${rule.id}'`)).rows[0].n, 0);
  const manual = (await db.query(draftSQL(1, manualEmailDraft))).rows[0].id;
  assert.ok(manual, "Manual template-free Draft remains independent of automation approval");
  await db.exec("RESET ROLE; SET ROLE authenticated");
  await fails("SELECT * FROM requirement_notification_rules", "42501");
  await fails("SELECT * FROM requirement_notification_readiness", "42501");
  await fails(approve(1, 4), "42501");
  await db.exec("RESET ROLE");
  await db.exec("UPDATE compliance_types SET compliance_name='NJ PWC' WHERE id=1");
  const eligibilityMigration = read("20261210_notification_eligibility_authority.sql");
  await fails(eligibilityMigration.replace(/COMMIT;\s*$/, "SELECT 1/0; COMMIT;"), "22012");
  await db.exec("ROLLBACK");
  await db.exec(eligibilityMigration);
  const configured = (await db.query(`SELECT eligibility_authority,revision FROM requirement_notification_rules WHERE id='${rule.id}'`)).rows[0];
  assert.equal(configured.eligibility_authority, "nj_pwc_monitoring");
  const withAuthority = (n, fields, authority) => `SELECT save_requirement_notification_rule_with_eligibility('${actor(n)}','${rule.id}',${input(fields)},${authority === null ? "NULL" : `'${authority}'`})`;
  const afterSeed = { ...base, revision: configured.revision, schedule_type: "non_expiring" };
  await db.exec("SET ROLE service_role");
  await fails(withAuthority(2, afterSeed, "current_requirement"), "42501");
  await fails(withAuthority(1, afterSeed, "arbitrary_function"), "22023");
  await db.exec(withAuthority(1, afterSeed, null));
  assert.equal((await db.query(`SELECT eligibility_authority FROM requirement_notification_rules WHERE id='${rule.id}'`)).rows[0].eligibility_authority, "nj_pwc_monitoring", "Older clients preserve authority");
  await db.exec(withAuthority(1, { ...afterSeed, revision: afterSeed.revision + 1 }, "current_requirement"));
  assert.equal((await db.query(`SELECT eligibility_authority FROM requirement_notification_rules WHERE id='${rule.id}'`)).rows[0].eligibility_authority, "current_requirement");
  await db.exec("RESET ROLE");
  assert.deepEqual((await db.query("SELECT * FROM notification_reminder_rules ORDER BY id")).rows, legacy);
  assert.deepEqual((await db.query("SELECT * FROM communication_channel_settings ORDER BY channel")).rows, channels);
  console.log("PASS: requirement configuration seeded from existing types and insurance items; disabled defaults/rollback; non-expiring/retired guards; explicit administrator revision approval, stale-edit invalidation, permission/concurrency checks, configurable intervals, manual template-free Draft; no automation or delivery changes.");
}
