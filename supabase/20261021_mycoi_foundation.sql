BEGIN;

CREATE TABLE public.mycoi_vendor_mappings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contractor_id INTEGER NOT NULL REFERENCES public.contractors(id) ON DELETE RESTRICT,
    raw_vendor_name TEXT NOT NULL CHECK (btrim(raw_vendor_name) <> ''),
    vendor_name_key TEXT GENERATED ALWAYS AS (lower(btrim(raw_vendor_name))) STORED,
    vendor_email TEXT,
    vendor_phone TEXT,
    last_imported_at TIMESTAMPTZ,
    import_reference TEXT,
    import_history_id INTEGER REFERENCES public.import_history(id) ON DELETE RESTRICT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, contractor_id)
);
CREATE UNIQUE INDEX mycoi_vendor_active_name
    ON public.mycoi_vendor_mappings(vendor_name_key) WHERE active;
CREATE INDEX mycoi_vendor_contractor ON public.mycoi_vendor_mappings(contractor_id);

CREATE TABLE public.mycoi_division_mappings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raw_division_name TEXT NOT NULL CHECK (btrim(raw_division_name) <> ''),
    division_name_key TEXT GENERATED ALWAYS AS (lower(btrim(raw_division_name))) STORED,
    leading_project_number TEXT GENERATED ALWAYS AS
        (substring(btrim(raw_division_name) FROM '^([0-9]+)(?:[[:space:]]|$|-)')) STORED,
    project_id INTEGER REFERENCES public.projects(id) ON DELETE RESTRICT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX mycoi_division_active_name
    ON public.mycoi_division_mappings(division_name_key) WHERE active;
CREATE INDEX mycoi_division_project ON public.mycoi_division_mappings(project_id);

CREATE TABLE public.mycoi_contractor_divisions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_mapping_id INTEGER NOT NULL REFERENCES public.mycoi_vendor_mappings(id) ON DELETE RESTRICT,
    division_mapping_id INTEGER NOT NULL REFERENCES public.mycoi_division_mappings(id) ON DELETE RESTRICT,
    compliance_status TEXT,
    last_imported_at TIMESTAMPTZ NOT NULL,
    import_reference TEXT NOT NULL CHECK (btrim(import_reference) <> ''),
    import_history_id INTEGER REFERENCES public.import_history(id) ON DELETE RESTRICT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (NOT is_current OR active),
    UNIQUE (id, vendor_mapping_id)
);
CREATE UNIQUE INDEX mycoi_contractor_division_current
    ON public.mycoi_contractor_divisions(vendor_mapping_id, division_mapping_id)
    WHERE active AND is_current;
CREATE INDEX mycoi_contractor_division_mapping ON public.mycoi_contractor_divisions(division_mapping_id);

CREATE TABLE public.mycoi_policies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contractor_id INTEGER NOT NULL REFERENCES public.contractors(id) ON DELETE RESTRICT,
    vendor_mapping_id INTEGER NOT NULL,
    policy_line TEXT NOT NULL CHECK (btrim(policy_line) <> ''),
    policy_line_key TEXT GENERATED ALWAYS AS
        (lower(regexp_replace(btrim(policy_line), '[[:space:]]+', ' ', 'g'))) STORED,
    policy_number TEXT,
    policy_number_key TEXT GENERATED ALWAYS AS (nullif(lower(btrim(policy_number)), '')) STORED,
    expiration_date DATE,
    expired BOOLEAN,
    source TEXT NOT NULL DEFAULT 'myCOI' CHECK (source = 'myCOI'),
    last_imported_at TIMESTAMPTZ NOT NULL,
    import_reference TEXT NOT NULL CHECK (btrim(import_reference) <> ''),
    import_history_id INTEGER REFERENCES public.import_history(id) ON DELETE RESTRICT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (vendor_mapping_id, contractor_id)
        REFERENCES public.mycoi_vendor_mappings(id, contractor_id) ON DELETE RESTRICT,
    CHECK (NOT is_current OR active),
    UNIQUE (id, vendor_mapping_id)
);
CREATE UNIQUE INDEX mycoi_policy_current_identity
    ON public.mycoi_policies(contractor_id, policy_line_key, policy_number_key, expiration_date)
    WHERE active AND is_current AND policy_number_key IS NOT NULL AND expiration_date IS NOT NULL;
CREATE INDEX mycoi_policy_vendor ON public.mycoi_policies(vendor_mapping_id);

CREATE TABLE public.mycoi_policy_divisions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id INTEGER NOT NULL,
    contractor_division_id INTEGER NOT NULL,
    vendor_mapping_id INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (policy_id, vendor_mapping_id)
        REFERENCES public.mycoi_policies(id, vendor_mapping_id) ON DELETE RESTRICT,
    FOREIGN KEY (contractor_division_id, vendor_mapping_id)
        REFERENCES public.mycoi_contractor_divisions(id, vendor_mapping_id) ON DELETE RESTRICT,
    UNIQUE (policy_id, contractor_division_id)
);
CREATE INDEX mycoi_policy_division_status ON public.mycoi_policy_divisions(contractor_division_id);

CREATE FUNCTION public.mycoi_touch_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

DO $$
DECLARE
    table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY[
        'mycoi_vendor_mappings', 'mycoi_division_mappings',
        'mycoi_contractor_divisions', 'mycoi_policies', 'mycoi_policy_divisions'
    ] LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
        EXECUTE format('REVOKE ALL ON public.%I FROM anon, authenticated', table_name);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE ON public.%I TO authenticated', table_name);
        EXECUTE format('GRANT USAGE ON SEQUENCE public.%I TO authenticated', table_name || '_id_seq');
        EXECUTE format(
            'CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (public.user_has_module_permission(''insurance'', ''view''))',
            table_name || '_select', table_name);
        EXECUTE format(
            'CREATE POLICY %I ON public.%I FOR INSERT TO authenticated WITH CHECK (public.user_has_module_permission(''insurance'', ''view'') AND public.user_has_module_permission(''insurance'', ''add''))',
            table_name || '_insert', table_name);
        EXECUTE format(
            'CREATE POLICY %I ON public.%I FOR UPDATE TO authenticated USING (public.user_has_module_permission(''insurance'', ''view'') AND public.user_has_module_permission(''insurance'', ''edit'')) WITH CHECK (public.user_has_module_permission(''insurance'', ''view'') AND public.user_has_module_permission(''insurance'', ''edit''))',
            table_name || '_update', table_name);
        IF table_name <> 'mycoi_policy_divisions' THEN
            EXECUTE format(
                'CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.mycoi_touch_updated_at()',
                table_name || '_updated_at', table_name);
        END IF;
    END LOOP;
END;
$$;

COMMENT ON TABLE public.mycoi_vendor_mappings IS
    'Separate myCOI identity only. Never updates contractor company_name, email, phone, or contacts. Retire mappings with active=false; do not delete.';
COMMENT ON COLUMN public.mycoi_division_mappings.project_id IS
    'NULL preserves an unresolved or ambiguous division for import review. Leading project number is only a hint, never an automatic match.';
COMMENT ON TABLE public.mycoi_contractor_divisions IS
    'Imported vendor/division compliance, independent of contractor_projects and legacy compliance calculations. Supersede with active=false,is_current=false before inserting a replacement.';
COMMENT ON TABLE public.mycoi_policies IS
    'myCOI-only policies. No issue/effective date is inferred. Multiple policies per line are supported. Preserve old rows by superseding rather than overwriting policy values.';
COMMENT ON COLUMN public.mycoi_policies.expired IS
    'Nullable expired flag supplied by myCOI, not inferred from expiration_date.';
COMMENT ON INDEX public.mycoi_policy_current_identity IS
    'Exact current identity only when policy number and expiration exist. Missing identity fields require Step 2 review, not type-only deduplication.';

COMMIT;
