CREATE TABLE compliance_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contractor_id INTEGER NOT NULL,
    compliance_type_id INTEGER NOT NULL,
    registration_number VARCHAR(200),
    effective_date DATE,
    expiration_date DATE,
    verified_date DATE,
    verified_by VARCHAR(200),
    verification_source VARCHAR(100),
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_compliance_records_contractor
        FOREIGN KEY (contractor_id) REFERENCES contractors(id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_compliance_records_type
        FOREIGN KEY (compliance_type_id) REFERENCES compliance_types(id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_compliance_dates
        CHECK (
            expiration_date IS NULL
            OR effective_date IS NULL
            OR expiration_date >= effective_date
        )
);

CREATE TABLE documents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contractor_id INTEGER NOT NULL,
    compliance_record_id INTEGER,
    document_name VARCHAR(200) NOT NULL,
    document_type VARCHAR(100) NOT NULL,
    storage_path VARCHAR(500) NOT NULL,
    original_file_name VARCHAR(255),
    storage_provider VARCHAR(50),
    file_size_bytes BIGINT CHECK (file_size_bytes IS NULL OR file_size_bytes >= 0),
    upload_date DATE NOT NULL DEFAULT CURRENT_DATE,
    expiration_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_documents_contractor
        FOREIGN KEY (contractor_id) REFERENCES contractors(id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_documents_compliance_record
        FOREIGN KEY (compliance_record_id) REFERENCES compliance_records(id)
        ON DELETE RESTRICT
);

CREATE TABLE activity_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contractor_id INTEGER NOT NULL,
    project_id INTEGER,
    activity_date DATE NOT NULL DEFAULT CURRENT_DATE,
    activity_type VARCHAR(100) NOT NULL,
    notes TEXT,
    follow_up_date DATE,
    created_by VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_activity_log_contractor
        FOREIGN KEY (contractor_id) REFERENCES contractors(id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_activity_log_project
        FOREIGN KEY (project_id) REFERENCES projects(id)
        ON DELETE RESTRICT
);

CREATE TABLE reminders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contractor_id INTEGER NOT NULL,
    compliance_record_id INTEGER NOT NULL,
    reminder_stage VARCHAR(20) NOT NULL
        CHECK (reminder_stage IN ('90 Day', '60 Day', '30 Day', 'Expired')),
    expiration_date_snapshot DATE NOT NULL,
    scheduled_date DATE NOT NULL,
    generated_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    sent_date TIMESTAMPTZ,
    delivery_status VARCHAR(50) NOT NULL DEFAULT 'Pending',
    acknowledged_date TIMESTAMPTZ,
    resolved_date TIMESTAMPTZ,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_reminders_contractor
        FOREIGN KEY (contractor_id) REFERENCES contractors(id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_reminders_compliance_record
        FOREIGN KEY (compliance_record_id) REFERENCES compliance_records(id)
        ON DELETE RESTRICT,
    CONSTRAINT uq_reminders_stage_cycle UNIQUE (
        compliance_record_id,
        reminder_stage,
        expiration_date_snapshot
    )
);

CREATE TABLE import_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name VARCHAR(250) NOT NULL,
    import_date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    imported_rows INTEGER NOT NULL DEFAULT 0 CHECK (imported_rows >= 0),
    successful_rows INTEGER NOT NULL DEFAULT 0 CHECK (successful_rows >= 0),
    failed_rows INTEGER NOT NULL DEFAULT 0 CHECK (failed_rows >= 0),
    notes TEXT,
    CONSTRAINT chk_import_history_consistency
        CHECK (successful_rows + failed_rows <= imported_rows)
);

