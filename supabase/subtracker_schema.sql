CREATE TABLE contractors (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR(200) NOT NULL,
    trade VARCHAR(150),
    contact_name VARCHAR(200),
    email VARCHAR(200),
    phone VARCHAR(50),
    notes TEXT,
    external_id VARCHAR(100),
    legacy_id VARCHAR(100),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_number VARCHAR(100) NOT NULL UNIQUE,
    project_name VARCHAR(200) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Pending', 'Completed', 'On Hold', 'Cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE contractor_projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contractor_id INTEGER NOT NULL,
    project_id INTEGER NOT NULL,
    assigned_date DATE NOT NULL DEFAULT CURRENT_DATE,
    removed_date DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_contractor_projects_contractor
        FOREIGN KEY (contractor_id) REFERENCES contractors(id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_contractor_projects_project
        FOREIGN KEY (project_id) REFERENCES projects(id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_contractor_project_dates
        CHECK (removed_date IS NULL OR removed_date >= assigned_date)
);

CREATE TABLE compliance_types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compliance_name VARCHAR(200) NOT NULL UNIQUE,
    requires_expiration BOOLEAN NOT NULL DEFAULT TRUE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

